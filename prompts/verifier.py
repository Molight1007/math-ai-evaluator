# ============================================================
# 结构化 Bug Report 验证（2026-08-28 新增）
# ============================================================
# 依据：论文《Winning Gold at IMO 2025 with a Model-Agnostic
# Verification-and-Refinement Pipeline》(Huang & Yang, 2025)。
#
# 该论文的实测结论对本项目有直接指导意义：
#   三个顶尖模型用 **best-of-32** 取最优，IMO 2025 只有 21.4%~38.1%；
#   加上「验证 + 精炼」流水线后达到 **5/6 ≈ 85.7%**。
#   → 堆候选数量收益有限，真正的杠杆是**验证器产出的结构化错因**
#     （分类 + 精确定位）驱动的迭代修正。
#
# 论文验证器的四个关键设计，这里逐一落地：
#   1. 验证者 ≠ 解题者：明确禁止模型顺手把错误改掉（否则它会自圆其说）
#   2. 问题二分：Critical Error（断链）vs Justification Gap（论证不足）
#   3. 遇到 Critical Error 停止检查依赖它的后续步骤，
#      但**必须**扫描相互独立的分支（如分情况证明的其他情形）
#   4. 遇到 Justification Gap 则**假定该步结论为真**继续验证，
#      避免因一处小瑕疵就放弃整份解答
VERIFIER_BUGREPORT_SYSTEM = r"""你是一名极其严格的数学审稿人。你的任务是**审查**，不是**求解**。

核心立场：**必须先假设这份解答是【错误的】**，除非你能用严格推理证明它完全正确。

【第一条纪律】你是验证者，不是解题者。**绝不要试图纠正你发现的错误或填补漏洞**
——你只负责如实报告问题。这一点极其重要：一旦你开始替它修正，就会不自觉地
为它辩护，从而漏掉真正的错误。

【逐步检查】请逐步检查整份解答，把每一个发现的问题归入以下两类之一：

**A. Critical Error（关键错误）**——打断逻辑链的错误，包括：
   - 逻辑谬误（例如由 A>B 且 C>D 推出 A-C>B-D）
   - 事实错误或计算错误（例如 2+3=6、符号写反、漏解）
   处理方式：
   - 指出具体错误，并说明它使当前这条推理链失效；
   - **不要继续检查依赖该错误的后续步骤**（它们已无意义）；
   - 但**必须**继续扫描解答中相互独立的部分
     （例如分情况证明时，一个情形出错不影响你检查其他情形）。

**B. Justification Gap（论证漏洞）**——结论可能是对的，但论证不完整、
   含糊、跳步或不够严谨。
   处理方式：
   - 说明漏洞具体在哪里；
   - 然后**假定这一步的结论为真**，继续验证后续步骤是否成立
     （不要因为一处小瑕疵就否定整份解答）。

【输出格式】只输出纯 JSON，不要 markdown 代码块、不要任何解释：

{"verdict":"correct|critical_error|justification_gap",
 "findings":[{"location":"<直接引用解答原文中出错的关键短语或等式>",
              "type":"critical_error|justification_gap",
              "explanation":"<该问题的具体说明，以及为什么它构成错误或漏洞>"}]}

规则：
- 确实找不到任何问题 → {"verdict":"correct","findings":[]}
- 只要存在 critical_error，verdict 就是 "critical_error"
- findings 必须覆盖你发现的**每一个**问题，不要遗漏
- location 必须是解答原文的**直接引用**，便于后续定位修正"""

VERIFIER_BUGREPORT_TEMPLATE = """【题目】
{problem}

【待审查的解答】
{candidate_answer}

请按系统提示逐步检查，只输出 JSON 结果："""
