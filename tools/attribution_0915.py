BATCH_NAME = {
    "B0": "B0 答案形式与完整性", "B1": "B1 客观题判断与审题",
    "B2": "B2 L1/L2 低难度推理", "B3": "B3 L3 困难推理",
    "B4": "B4 L4 极难题", "GG": "GG gold 疑误/争议", "JJ": "JJ 判分口径缺口",
}


def main() -> None:
    ids = [r[0] for r in ROWS]
    assert len(ROWS) == 89, "行数应为 89，实际 %d" % len(ROWS)
    assert len(set(ids)) == 89, "题号重复: %s" % [i for i, c in Counter(ids).items() if c > 1]

    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_jsonl = os.path.join(here, "results", "归因明细_0915.jsonl")
    os.makedirs(os.path.dirname(out_jsonl), exist_ok=True)
    with open(out_jsonl, "w", encoding="utf-8") as f:
        for tid, batch, lvl, pred, gold, cls, why in ROWS:
            f.write(json.dumps({
                "id": "official112-%s" % tid, "batch": batch, "level": lvl,
                "pred": pred, "gold": gold, "cls": cls, "evidence": why,
                "scope": "main48" if batch in ("B2", "B3") and cls in MECH_ORDER else "other",
            }, ensure_ascii=False) + "\n")

    print("=== 表 1 · 批次分布（台账 7 批，合计 89）===")
    bc = Counter(r[1] for r in ROWS)
    print("| 批次 | 题数 | 占比 |")
    print("|---|---|---|")
    for b in ["B0", "B1", "B2", "B3", "B4", "GG", "JJ"]:
        print("| %s | %d | %.1f%% |" % (BATCH_NAME[b], bc[b], bc[b] / 89 * 100))
    print("| **合计** | **%d** | **100.0%%** |" % sum(bc.values()))

    print("\n=== 表 2 · 五类机理（仅「第一项」= B2+B3 内 48 题有效）===")
    main_rows = [r for r in ROWS if r[1] in ("B2", "B3") and r[5] in MECH_ORDER]
    mc = Counter(r[5] for r in main_rows)
    print("| 类别 | 题数 | 占 48 |")
    print("|---|---|---|")
    for k in MECH_ORDER:
        print("| %s %s | %d | %.1f%% |" % (k, MECH_NAME[k], mc[k], mc[k] / 48 * 100))
    print("| **合计** | **%d** | **100.1%%** |" % sum(mc.values()))
    print("（分母 48 = 第一项 50 − 060 判分口径 − 072 答案形式）")

    print("\n=== 表 3 · 全量 89 题按机理/性质归并（闭合校验）===")
    gc = Counter()
    for r in ROWS:
        c = r[5]
        if c in MECH_ORDER:
            gc["A-E 机理类"] += 1
        elif c == "FORM":
            gc["答案形式/完整性"] += 1
        elif c == "OBJ":
            gc["客观题知识/审题"] += 1
        elif c == "NONE":
            gc["完全无输出"] += 1
        elif c == "GG":
            gc["gold 疑误/口径（非能力）"] += 1
        elif c == "JJ":
            gc["判分器缺口（非能力）"] += 1
    print("| 性质 | 题数 | 占 89 |")
    print("|---|---|---|")
    for k, v in gc.most_common():
        print("| %s | %d | %.1f%% |" % (k, v, v / 89 * 100))
    print("| **合计** | **%d** | **100.0%%** |" % sum(gc.values()))

    print("\n=== 表 4 · 三维切分（建模/推理/计算，仅第一项 48 题）===")
    d3 = {
        "建模错误": mc["A"],
        "推理错误": mc["B"] + mc["C"] + mc["D"],
        "计算错误": mc["E"],
    }
    print("| 维度 | 题数 | 占 48 | 对应五类 |")
    print("|---|---|---|---|")
    for k, v in d3.items():
        corr = {"建模错误": "A", "推理错误": "B+C+D", "计算错误": "E"}[k]
        print("| %s | %d | %.1f%% | %s |" % (k, v, v / 48 * 100, corr))
    print("| **合计** | **%d** | **100.0%%** | — |" % sum(d3.values()))

    print("\n=== 表 5 · 「所谓计数模型」的结构错 vs 数错 ===")
    combo = mc["A"] + mc["B"]
    print("| 细分 | 题数 | 占 A+B(%d) |" % combo)
    print("|---|---|---|")
    print("| 结构选错（A 思路/建模） | %d | %.0f%% |" % (mc["A"], mc["A"] / combo * 100))
    print("| 结构对、数错（B 计数/枚举） | %d | %.0f%% |" % (mc["B"], mc["B"] / combo * 100))

    print("\n=== 表 6 · A 类量级指纹（|现答/正解| 可核算）===")
    for tid, _b, _l, pred, gold, cls, why in ROWS:
        if cls == "A" and "量级" in why:
            print("  %s  %s → %s   （%s）" % (tid, pred, gold, why))

    print("\n=== 已写出 ===\n  %s" % out_jsonl)


